import assert from 'node:assert/strict';
import {createHmac} from 'node:crypto';
process.env.SESSION_SECRET='test-only-secret';
const {valid,key,purchase,default:handler}=await import('./api/account.js');
const token=expiry=>`${expiry}.${createHmac('sha256',process.env.SESSION_SECRET).update(String(expiry)).digest('hex')}`;
assert(valid(token(Date.now()+10000)));
assert(!valid(token(Date.now()-1)));
assert(!valid(token(Date.now()+10000).replace(/.$/,'z')));
assert(purchase({transaction:'Purchase'}));
assert(!purchase({transaction:'Purchase',needs_review:true}));
assert(!purchase({transaction:'Sale'}));
assert.equal(key('quiver',{id:42,asset:'Before'}),key('quiver',{id:42,asset:'Corrected'}));
assert.notEqual(key('quiver',{id:42}),key('quiver',{id:43}));
const res={setHeader(){},end(body){this.body=JSON.parse(body);}};
await handler({url:'/api/account?action=watch',method:'POST',headers:{},body:{source:'quiver',name:'Nancy Pelosi'}},res);
assert.equal(res.statusCode,401);
assert.equal(res.body.error,'Sign in to manage email alerts.');
process.env.CRON_SECRET='test-cron-secret';
await handler({url:'/api/account?action=cron',method:'GET',headers:{authorization:'Bearer wrong'}},res);
assert.equal(res.statusCode,401);
console.log('PASS: session validation, purchase classification, duplicate identity and private watchlist boundary');
